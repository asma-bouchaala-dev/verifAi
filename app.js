const API_BASE = "https://verifai-backend-59h5.onrender.com";

function store(key, value) {
  try { localStorage.setItem("verifai:" + key, value); } catch (e) {}
}
function load(key) {
  try { return localStorage.getItem("verifai:" + key); } catch (e) { return null; }
}

let lang = "en";
let theme = "light";
let lastResult = null;
let lastClaim = "";
let isLoading = false;

// ---------- Helpers ----------

function t() {
  return STRINGS[lang];
}

function el(tag, className, text) {
  const element = document.createElement(tag);

  if (className) {
    element.className = className;
  }

  if (text !== undefined) {
    element.textContent = text;
  }

  return element;
}

function getVerdict(verdict) {
  if (verdict === "needs_review") {
    return "review";
  }

  if (
    verdict === "supported" ||
    verdict === "contradicted" ||
    verdict === "insufficient"
  ) {
    return verdict;
  }

  return "review";
}

function getValidSources(result) {
  const sources = Array.isArray(result.sources)
    ? result.sources
    : [];

  return sources.filter((source) => {
    try {
      const url = new URL(source.url);
      return url.protocol === "https:";
    } catch {
      return false;
    }
  });
}

// ---------- Copy result ----------

function buildShareText() {
  if (!lastResult) return "";

  const verdict = getVerdict(lastResult.verdict);
  const sources = getValidSources(lastResult);

  const lines = [
    "VerifAI",
    "",
    t().claimTitle + ":",
    lastClaim,
    "",
    "Verdict:",
    t().verdicts[verdict],
    "",
    t().explanation + ":",
    lastResult.explanation || ""
  ];

  if (lastResult.evidence_summary) {
    lines.push(
      "",
      t().evidence + ":",
      lastResult.evidence_summary
    );
  }

  lines.push("", t().sources + ":");

  if (sources.length) {
    sources.forEach((source) => {
      lines.push(
        "- " + (source.title || source.domain || source.url),
        source.url
      );
    });
  } else {
    lines.push(t().noSources);
  }

  if (lastResult.limitations) {
    lines.push(
      "",
      t().limitations + ":",
      lastResult.limitations
    );
  }

  lines.push(
    "",
    t().disclaimer,
    "",
    "Built by Sky",
    "VerifAI"
  );

  return lines.join("\n");
}

async function copyResult() {
  try {
    const text = buildShareText();

    await navigator.clipboard.writeText(text);

    const button = document.getElementById("copyResultBtn");

    if (button) {
      button.textContent = t().copied;

      setTimeout(() => {
        if (button.isConnected) {
          button.textContent = t().copy;
        }
      }, 2000);
    }
  } catch (error) {
    console.error("Copy error:", error);
    alert(t().copyError);
  }
}

// ---------- Create share image ----------

function wrapText(context, text, maxWidth) {
  const words = String(text || "").split(/\s+/);
  const lines = [];
  let line = "";

  for (const word of words) {
    const testLine = line ? line + " " + word : word;

    if (
      context.measureText(testLine).width > maxWidth &&
      line
    ) {
      lines.push(line);
      line = word;
    } else {
      line = testLine;
    }
  }

  if (line) {
    lines.push(line);
  }

  return lines;
}

function drawWrappedText(
  context,
  text,
  x,
  y,
  maxWidth,
  lineHeight,
  maxLines = 8
) {
  const lines = wrapText(context, text, maxWidth);
  const visibleLines = lines.slice(0, maxLines);

  visibleLines.forEach((line, index) => {
    context.fillText(line, x, y + index * lineHeight);
  });

  if (lines.length > maxLines) {
    context.fillText("...", x, y + maxLines * lineHeight);
    return y + (maxLines + 1) * lineHeight;
  }

  return y + visibleLines.length * lineHeight;
}

function createShareCanvas() {
  return new Promise((resolve, reject) => {
    try {
      if (!lastResult || lastResult.error) {
        reject(new Error("No valid result to share"));
        return;
      }

      const verdict = getVerdict(lastResult.verdict);

      const colors = {
        supported: {
          background: "#F6FBF7",
          card: "#E2F2E7",
          text: "#285C3A",
          border: "#B7DCC3"
        },

        contradicted: {
          background: "#FFFAFA",
          card: "#F9E2E2",
          text: "#923D42",
          border: "#EBC1C1"
        },

        insufficient: {
          background: "#FFFCF5",
          card: "#FFF2D6",
          text: "#805C20",
          border: "#EBD9AD"
        },

        review: {
          background: "#F8FAFE",
          card: "#E5ECF8",
          text: "#385783",
          border: "#C5D4EC"
        }
      };

      const palette = colors[verdict];

      const canvas = document.createElement("canvas");
      const context = canvas.getContext("2d");

      if (!context) {
        reject(new Error("Canvas unavailable"));
        return;
      }

      const width = 1000;
      const padding = 65;
      const contentWidth = width - padding * 2;
      const isArabic = lang === "ar";

      canvas.width = width;
      canvas.height = 10000;

      function setupContext() {
        context.direction = isArabic ? "rtl" : "ltr";
        context.textAlign = isArabic ? "right" : "left";
        context.lineJoin = "round";
        context.lineCap = "round";
      }

      function drawText(text, x, y, font, color) {
        context.font = font;
        context.fillStyle = color;
        context.fillText(text, x, y);
      }

      function drawSectionTitle(text, y) {
        drawText(
          text,
          isArabic ? width - padding : padding,
          y,
          "bold 30px Arial",
          "#0b5cab"
        );

        return y + 48;
      }

      function drawParagraph(text, y, fontSize = 25, lineHeight = 38) {
        context.font = `${fontSize}px Arial`;
        context.fillStyle = "#344054";

        return drawWrappedText(
          context,
          text,
          isArabic ? width - padding : padding,
          y,
          contentWidth,
          lineHeight,
          100
        );
      }

      function drawCard(x, y, cardWidth, cardHeight, fill, border) {
        context.fillStyle = fill;
        context.strokeStyle = border;
        context.lineWidth = 2;

        context.beginPath();
        context.roundRect(
          x,
          y,
          cardWidth,
          cardHeight,
          22
        );
        context.fill();
        context.stroke();
      }

      function drawAll() {
        setupContext();

        context.clearRect(0, 0, width, canvas.height);

        context.fillStyle = palette.background;
        context.fillRect(0, 0, width, canvas.height);

        let y = 95;

        // Header

        drawText(
          "VerifAI",
          isArabic ? width - padding : padding,
          y,
          "bold 48px Arial",
          "#0b5cab"
        );

        y += 45;

        drawText(
          "Health Claim Check",
          isArabic ? width - padding : padding,
          y,
          "24px Arial",
          "#667085"
        );

        y += 65;

        // Claim card

        context.font = "30px Arial";

        const claimLines = wrapText(
          context,
          lastClaim,
          contentWidth - 60
        );

        const claimHeight = Math.max(
          170,
          115 + claimLines.length * 43
        );

        drawCard(
          padding,
          y,
          contentWidth,
          claimHeight,
          "#FFFFFF",
          "#D5DEE8"
        );

        drawText(
          t().claimTitle,
          isArabic ? width - padding - 30 : padding + 30,
          y + 48,
          "bold 25px Arial",
          "#667085"
        );

        drawText(
          "",
          padding + 30,
          y + 90,
          "25px Arial",
          "#344054"
        );

        context.font = "30px Arial";
        context.fillStyle = "#344054";

        claimLines.forEach((line, index) => {
          context.fillText(
            line,
            isArabic ? width - padding - 30 : padding + 30,
            y + 100 + index * 43
          );
        });

        y += claimHeight + 35;

        // Verdict card

        drawCard(
          padding,
          y,
          contentWidth,
          110,
          palette.card,
          palette.border
        );

        drawText(
          t().verdicts[verdict],
          isArabic ? width - padding - 30 : padding + 30,
          y + 68,
          "bold 31px Arial",
          palette.text
        );

        y += 155;

        // Explanation

        y = drawSectionTitle(t().explanation, y);

        y = drawParagraph(
          lastResult.explanation || "",
          y
        );

        // Evidence summary

        if (lastResult.evidence_summary) {
          y += 30;

          y = drawSectionTitle(t().evidence, y);

          y = drawParagraph(
            lastResult.evidence_summary,
            y
          );
        }

        // Sources

        y += 30;

        y = drawSectionTitle(t().sources, y);

        const sources = getValidSources(lastResult);

        if (sources.length) {
          context.font = "21px Arial";
          context.fillStyle = "#344054";

          sources.slice(0, 4).forEach((source) => {
            const title =
              source.title ||
              source.domain ||
              source.url;

            y = drawWrappedText(
              context,
              "• " + title,
              isArabic ? width - padding : padding,
              y,
              contentWidth,
              30,
              3
            );

            y += 8;

            context.font = "17px Arial";
            context.fillStyle = "#527FA8";

            y = drawWrappedText(
              context,
              source.url,
              isArabic ? width - padding : padding,
              y,
              contentWidth,
              25,
              2
            );

            y += 18;

            context.font = "21px Arial";
            context.fillStyle = "#344054";
          });
        } else {
          y = drawParagraph(t().noSources, y, 21, 30);
        }

        // Limitations

        if (lastResult.limitations) {
          y += 15;

          y = drawSectionTitle(t().limitations, y);

          y = drawParagraph(
            lastResult.limitations,
            y,
            20,
            28
          );
        }

        // Disclaimer

        y += 35;

        context.strokeStyle = "#D5DEE8";
        context.lineWidth = 2;
        context.beginPath();
        context.moveTo(padding, y);
        context.lineTo(width - padding, y);
        context.stroke();

        y += 35;

        y = drawParagraph(
          t().disclaimer,
          y,
          18,
          27
        );

        // Footer

        y += 35;

        drawText(
          "Built by Sky",
          isArabic ? width - padding : padding,
          y,
          "bold 24px Arial",
          "#0b5cab"
        );

        y += 35;

        drawText(
          t().generated,
          isArabic ? width - padding : padding,
          y,
          "18px Arial",
          "#667085"
        );

        return y + padding;
      }

      // First pass calculates the required height.

      const requiredHeight = drawAll();

      // Second pass redraws the image at its actual height.

      canvas.height = Math.ceil(requiredHeight);

      drawAll();

      resolve(canvas);

    } catch (error) {
      reject(error);
    }
  });
}

async function shareAsImage() {
  try {
    const canvas = await createShareCanvas();

    const blob = await new Promise((resolve, reject) => {
      canvas.toBlob((result) => {
        if (result) {
          resolve(result);
        } else {
          reject(new Error("Image generation failed"));
        }
      }, "image/png");
    });

    const file = new File(
      [blob],
      "VerifAI-result.png",
      { type: "image/png" }
    );

    // Use native sharing when supported

    if (
      navigator.share &&
      navigator.canShare &&
      navigator.canShare({ files: [file] })
    ) {
      await navigator.share({
        title: "VerifAI",
        text: t().generated,
        files: [file]
      });

      return;
    }

    // Otherwise download the image

    const imageUrl = URL.createObjectURL(blob);

    const link = document.createElement("a");
    link.href = imageUrl;
    link.download = "VerifAI-result.png";

    document.body.appendChild(link);
    link.click();
    link.remove();

    setTimeout(() => {
      URL.revokeObjectURL(imageUrl);
    }, 3000);

  } catch (error) {
    if (error.name === "AbortError") {
      return;
    }

    console.error("Image sharing error:", error);
    alert(t().imageError);
  }
}

// ---------- Display result ----------

function renderResult(result) {
  const box = document.getElementById("result");

  box.innerHTML = "";

  if (!result) {
    box.hidden = true;
    return;
  }

  box.hidden = false;

  if (result.error) {
    box.className = "review";
    box.appendChild(el("p", "error", result.error));
    return;
  }

  const verdict = getVerdict(result.verdict);

  box.className = verdict;

  // Verdict

  box.appendChild(
    el("span", "badge " + verdict, t().verdicts[verdict])
  );

  // Explanation

  box.appendChild(el("h2", "", t().explanation));

  box.appendChild(
    el("p", "", result.explanation || "")
  );

  // Evidence summary

  if (result.evidence_summary) {
    box.appendChild(el("h2", "", t().evidence));

    box.appendChild(
      el("p", "", result.evidence_summary)
    );
  }

  // Sources

  box.appendChild(el("h2", "", t().sources));

  const validSources = getValidSources(result);

  if (validSources.length === 0) {
    box.appendChild(
      el("p", "muted small", t().noSources)
    );
  } else {
    const list = el("ul");

    validSources.forEach((source) => {
      const item = el("li");

      const link = el(
        "a",
        "",
        source.title || source.domain || "Medical source"
      );

      link.href = source.url;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

      item.appendChild(link);
      list.appendChild(item);
    });

    box.appendChild(list);
  }

  // Limitations

  if (result.limitations) {
    box.appendChild(el("h2", "", t().limitations));

    box.appendChild(
      el("p", "", result.limitations)
    );
  }

  // Sharing buttons

  const shareRow = el("div", "share-actions");

  const copyButton = el(
    "button",
    "",
    t().copy
  );

  copyButton.id = "copyResultBtn";
  copyButton.type = "button";

  copyButton.addEventListener("click", copyResult);

  const imageButton = el(
    "button",
    "",
    t().image
  );

  imageButton.id = "shareImageBtn";
  imageButton.type = "button";

  imageButton.addEventListener("click", shareAsImage);

  shareRow.appendChild(copyButton);
  shareRow.appendChild(imageButton);

  box.appendChild(shareRow);
}

// ---------- Language ----------

function applyLanguage() {
  document.documentElement.lang = lang;

  document.documentElement.dir =
    lang === "ar" ? "rtl" : "ltr";

  document.getElementById("langBtn").textContent =
    lang === "ar" ? "English" : "العربية";

  document.getElementById("themeBtn").title = t().theme;
  document.getElementById("themeBtn").setAttribute(
    "aria-label",
    t().theme
  );

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;

    if (t()[key] !== undefined) {
      element.textContent = t()[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;

    if (t()[key] !== undefined) {
      element.placeholder = t()[key];
    }
  });

  if (isLoading) {
    renderLoading();
  } else {
    renderResult(lastResult);
  }
}

// ---------- Theme ----------

function applyTheme() {
  document.body.dataset.theme = theme;

  const themeButton = document.getElementById("themeBtn");

  if (themeButton) {
    themeButton.textContent =
      theme === "dark" ? "☀️" : "🌙";

    themeButton.title = t().theme;
    themeButton.setAttribute("aria-label", t().theme);
  }
}

async function toggleTheme() {
  theme = theme === "light" ? "dark" : "light";

  applyTheme();

  store("theme", theme);
}

// ---------- Loading state ----------

function renderLoading() {
  const box = document.getElementById("result");

  box.innerHTML = "";
  box.className = "review";
  box.hidden = false;

  box.appendChild(
    el("p", "loading", t().loading)
  );
}

// ---------- Connect to backend ----------

async function assessClaim(claimText) {
  const response = await fetch(
    API_BASE + "/assess",
    {
      method: "POST",

      headers: {
        "Content-Type": "application/json"
      },

      body: JSON.stringify({
        claim: claimText
      })
    }
  );

  if (!response.ok) {
    throw new Error("Server error: " + response.status);
  }

  const data = await response.json();

  if (!data || !data.verdict) {
    throw new Error("Invalid server response");
  }

  return data;
}

// ---------- Main assessment ----------

async function handleAssessment() {
  if (isLoading) {
    return;
  }

  const claimText = document
    .getElementById("claim")
    .value
    .trim();

  if (!claimText) {
    lastResult = {
      error: t().empty
    };

    renderResult(lastResult);
    return;
  }

  isLoading = true;
  lastResult = null;
  lastClaim = claimText;

  const button = document.getElementById("assessBtn");

  button.disabled = true;

  renderLoading();

  const wakingTimer = setTimeout(() => {
    if (isLoading) {
      const note = el("p", "muted small", t().waking);
      document.getElementById("result").appendChild(note);
    }
  }, 8000);

  try {
    const result = await assessClaim(claimText);

    lastResult = result;

    renderResult(result);

  } catch (error) {
    console.error("VerifAI assessment error:", error);

    lastResult = {
      error: t().error
    };

    renderResult(lastResult);

  } finally {
    clearTimeout(wakingTimer);

    isLoading = false;

    button.disabled = false;
  }
}

// ---------- Start app ----------

function init() {
  const claimInput = document.getElementById("claim");

  const savedLang = load("lang");
  const savedTheme = load("theme");

  if (savedLang === "ar" || savedLang === "en") {
    lang = savedLang;
  } else if ((navigator.language || "").toLowerCase().startsWith("ar")) {
    lang = "ar";
  }

  if (savedTheme === "dark" || savedTheme === "light") {
    theme = savedTheme;
  } else if (window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches) {
    theme = "dark";
  }

  applyTheme();
  applyLanguage();

  // Wake the free-tier server early so the first check is faster.
  fetch(API_BASE, { mode: "no-cors" }).catch(() => {});

  document.getElementById("langBtn").addEventListener("click", () => {
    lang = lang === "en" ? "ar" : "en";
    store("lang", lang);
    applyLanguage();
  });

  document.getElementById("themeBtn").addEventListener("click", toggleTheme);
  document.getElementById("assessBtn").addEventListener("click", handleAssessment);

  document.getElementById("clearBtn").addEventListener("click", () => {
    claimInput.value = "";
    lastResult = null;
    lastClaim = "";
    renderResult(null);
    claimInput.focus();
  });

  // Ctrl/Cmd + Enter submits
  claimInput.addEventListener("keydown", (e) => {
    if ((e.ctrlKey || e.metaKey) && e.key === "Enter") handleAssessment();
  });
}

init();
